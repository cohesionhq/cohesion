use std::{fs, path::PathBuf};

use clap::Subcommand;
use cohesion_core::protocol::{DocumentationRequest, RunScriptRequest};

use crate::{cli_context::Context, cli_error::CliError};

#[derive(Subcommand)]
pub enum ScriptCommand {
    /// Run a script file on cohesiond and print its result.
    Run {
        /// Path to the script.
        file: PathBuf,
    },
    /// Create a starter script, with `cohesion.d.ts` type definitions next to it.
    New {
        /// Path of the new script.
        file: PathBuf,
        /// Skip writing `cohesion.d.ts`.
        #[arg(long = "no-types")]
        skip_types: bool,
        /// Replace FILE if it already exists.
        #[arg(short = 'f', long)]
        force: bool,
    },
    Typegen {
        dir: PathBuf,
    },
}

pub async fn run(ctx: &Context, command: ScriptCommand) -> Result<(), CliError> {
    match command {
        ScriptCommand::Run { file } => run_file(ctx, file).await,
        ScriptCommand::New {
            file,
            skip_types,
            force,
        } => new(ctx, file, skip_types, force).await,
        ScriptCommand::Typegen { dir } => gen_types(ctx, dir).await,
    }
}

pub async fn run_file(ctx: &Context, file: PathBuf) -> Result<(), CliError> {
    let script = fs::read_to_string(file).map_err(CliError::CannotReadFile)?;
    let result = ctx.call(RunScriptRequest { script }).await?;
    println!("{}", result.0);
    Ok(())
}

/// Writes a starter script at `file`, and unless `skip_types`, the type definitions it
/// references next to it. Refuses to replace an existing script unless `force`.
async fn new(ctx: &Context, file: PathBuf, skip_types: bool, force: bool) -> Result<(), CliError> {
    if file.exists() && !force {
        return Err(CliError::FileExists(file));
    }
    let header = "// Generated by Cohesion, for use with the Cohesion API.\n";
    if skip_types {
        fs::write(&file, header).map_err(CliError::CannotWriteFile)?;
        println!("Created {}.", file.display());
        return Ok(());
    }

    let types = file.with_file_name("cohesion.d.ts");
    let result = ctx.call(DocumentationRequest).await?;
    fs::write(&types, result.documentation).map_err(CliError::CannotWriteFile)?;
    let script = format!("/// <reference path=\"./cohesion.d.ts\" />\n{header}");
    fs::write(&file, script).map_err(CliError::CannotWriteFile)?;
    println!(
        "Created {} with type definitions in {}.",
        file.display(),
        types.display()
    );
    Ok(())
}

async fn gen_types(ctx: &Context, dir: PathBuf) -> Result<(), CliError> {
    let types = dir.join("cohesion.d.ts");
    let result = ctx.call(DocumentationRequest).await?;
    fs::write(&types, result.documentation).map_err(CliError::CannotWriteFile)?;
    Ok(())
}
