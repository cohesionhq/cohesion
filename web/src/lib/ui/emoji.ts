// The emoji the picker offers, grouped as the picker shows them, each with the
// words a search matches. A curated set rather than all of Unicode: these
// stand in for a workspace's or agent's initial, so faces, flags and skin
// tones beyond the defaults add little.

export interface Emoji {
	char: string;
	/** Lowercase words a search matches, space-separated. */
	words: string;
}

export interface EmojiGroup {
	name: string;
	/** The emoji the group's tab shows. */
	icon: string;
	emoji: Emoji[];
}

function group(name: string, entries: [string, string][]): EmojiGroup {
	return {
		name,
		icon: entries[0][0],
		emoji: entries.map(([char, words]) => ({ char, words }))
	};
}

