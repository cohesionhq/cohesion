/**
 * The emoji whose words start with every word of `query`, in picker order.
 * Matching is by word prefix, so "ca" finds 🐱 cat and 📅 calendar but not
 * 🦆 duck.
 */
export function searchEmoji(query: string): Emoji[] {
	const terms = query.toLowerCase().split(/\s+/).filter(Boolean);
	if (terms.length === 0) return [];
	return EMOJI_GROUPS.flatMap((g) => g.emoji).filter((e) => {
		const words = e.words.split(' ');
		return terms.every((t) => words.some((w) => w.startsWith(t)));
	});
}

/** Whether `text` holds an emoji, so a pasted one the set lacks can still be used. */
export function hasEmoji(text: string): boolean {
	return /\p{Extended_Pictographic}/u.test(text);
}
