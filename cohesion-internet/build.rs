//! Writes Coherence's rules (`coherence/rules/*.json`, in file-name order)
//! and hints (`coherence/hints.json`) as the Rust source of `RULES` and
//! `HINTS`: `static` slices of `const` constructors, so the binary carries
//! them built and nothing is parsed or allocated when a page is read. A
//! rule file is a JSON array of `{ "about", "trigger", "action" }`, its
//! trigger and action spelled as `coherence::rule`'s enums in snake case;
//! a mistake in one is a build error naming the file.

use std::fmt::Write as _;
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;

fn main() {
    let dir = Path::new("coherence");
    println!("cargo::rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = fs::read_dir(dir.join("rules"))
        .expect("coherence/rules is readable")
        .map(|entry| entry.expect("a rule file is readable").path())
        .filter(|path| {
            path.extension()
                .is_some_and(|extension| extension == "json")
        })
        .collect();
    files.sort();
    let mut out = String::from(
        "// Generated by build.rs from coherence/rules/*.json and coherence/hints.json.\n\n",
    );
    out.push_str("pub(crate) static RULES: &[Rule] = &[\n");
    for file in &files {
        let name = file.file_name().unwrap_or_default().to_string_lossy();
        for rule in read::<RuleSpec>(file) {
            comment(&mut out, &name, rule.about.as_deref());
            let _ = writeln!(out, "    {},", rule.rust());
        }
    }
    out.push_str("];\n\npub(crate) static HINTS: &[Hint] = &[\n");
    for hint in read::<HintSpec>(&dir.join("hints.json")) {
        comment(&mut out, "hints.json", hint.about.as_deref());
        let _ = writeln!(out, "    {},", hint.rust());
    }
    out.push_str("];\n");
    let target = PathBuf::from(std::env::var("OUT_DIR").expect("cargo sets OUT_DIR"))
        .join("coherence_rules.rs");
    fs::write(target, out).expect("OUT_DIR is writable");
}

/// The entries of the JSON array in `path`.
fn read<T: for<'de> Deserialize<'de>>(path: &Path) -> Vec<T> {
    let text =
        fs::read_to_string(path).unwrap_or_else(|error| panic!("{}: {error}", path.display()));
    serde_json::from_str(&text).unwrap_or_else(|error| panic!("{}: {error}", path.display()))
}

/// A comment saying where a rule came from and what it is for.
fn comment(out: &mut String, file: &str, about: Option<&str>) {
    let _ = writeln!(
        out,
        "    // {file}: {}",
        about.unwrap_or("").replace('\n', " ")
    );
}

/// `text` as a Rust string literal.
fn literal(text: &str) -> String {
    format!("{text:?}")
}

/// `items` as a Rust slice of string literals.
fn list(items: &[String]) -> String {
    let items: Vec<String> = items.iter().map(|item| literal(item)).collect();
    format!("&[{}]", items.join(", "))
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct RuleSpec {
    about: Option<String>,
    trigger: TriggerSpec,
    action: ActionSpec,
}

impl RuleSpec {
    fn rust(&self) -> String {
        let trigger = self.trigger.rust();
        match &self.action {
            ActionSpec::Delete => format!("Rule::delete({trigger})"),
            ActionSpec::Unwrap => format!("Rule::unwrap({trigger})"),
            ActionSpec::DeleteSection => format!("Rule::delete_section({trigger})"),
            ActionSpec::StripNames => format!("Rule::strip_names({trigger})"),
            ActionSpec::LinkTo(embed) => format!("Rule::link_to({trigger}, {})", embed.rust()),
            ActionSpec::SourceFrom(attribute) => {
                format!("Rule::source_from({trigger}, {})", literal(attribute))
            }
        }
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct HintSpec {
    about: Option<String>,
    trigger: TriggerSpec,
    /// What the hint adds to an element's weight: positive for, negative
    /// against.
    weight: i32,
}

impl HintSpec {
    fn rust(&self) -> String {
        let trigger = self.trigger.rust();
        match self.weight {
            weight if weight >= 0 => format!("Hint::favor({trigger}, {weight})"),
            weight => format!("Hint::against({trigger}, {})", weight.unsigned_abs()),
        }
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
enum ActionSpec {
    Delete,
    Unwrap,
    DeleteSection,
    StripNames,
    LinkTo(EmbedSpec),
    SourceFrom(String),
}

#[derive(Deserialize)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
enum TriggerSpec {
    Selector(String),
    ElementWithId(String),
    ElementWithClass(String),
    Named(NameSpec),
    Around { inner: String, outer: String },
    Heading(PhraseSpec),
    Link(PhraseSpec),
    LinkList(PhraseSpec),
    SmallImage(u32),
    ImageFrom(AddressSpec),
    ImageLink,
    GlyphLink,
    PictureWrapper,
    BareCode,
    Any(Vec<TriggerSpec>),
}

impl TriggerSpec {
    fn rust(&self) -> String {
        match self {
            TriggerSpec::Selector(selector) => format!("Trigger::Selector({})", literal(selector)),
            TriggerSpec::ElementWithId(id) => format!("Trigger::ElementWithId({})", literal(id)),
            TriggerSpec::ElementWithClass(class) => {
                format!("Trigger::ElementWithClass({})", literal(class))
            }
            TriggerSpec::Named(name) => format!("Trigger::Named({})", name.rust()),
            TriggerSpec::Around { inner, outer } => {
                format!("Trigger::Around({}, {})", literal(inner), literal(outer))
            }
            TriggerSpec::Heading(phrase) => format!("Trigger::Heading({})", phrase.rust()),
            TriggerSpec::Link(phrase) => format!("Trigger::Link({})", phrase.rust()),
            TriggerSpec::LinkList(phrase) => format!("Trigger::LinkList({})", phrase.rust()),
            TriggerSpec::SmallImage(size) => format!("Trigger::SmallImage({size})"),
            TriggerSpec::ImageFrom(address) => format!("Trigger::ImageFrom({})", address.rust()),
            TriggerSpec::ImageLink => "Trigger::ImageLink".to_string(),
            TriggerSpec::GlyphLink => "Trigger::GlyphLink".to_string(),
            TriggerSpec::PictureWrapper => "Trigger::PictureWrapper".to_string(),
            TriggerSpec::BareCode => "Trigger::BareCode".to_string(),
            TriggerSpec::Any(triggers) => {
                let triggers: Vec<String> = triggers.iter().map(TriggerSpec::rust).collect();
                format!("Trigger::Any(&[{}])", triggers.join(", "))
            }
        }
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
enum NameSpec {
    Part(Vec<String>),
    Prefix(Vec<String>),
    Run(Vec<String>),
    Pair(Vec<String>, Vec<String>),
}

impl NameSpec {
    fn rust(&self) -> String {
        match self {
            NameSpec::Part(parts) => format!("Name::Part({})", list(parts)),
            NameSpec::Prefix(prefixes) => format!("Name::Prefix({})", list(prefixes)),
            NameSpec::Run(run) => format!("Name::Run({})", list(run)),
            NameSpec::Pair(first, second) => {
                format!("Name::Pair({}, {})", list(first), list(second))
            }
        }
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
enum PhraseSpec {
    Is(Vec<String>),
    StartsWith(String),
    EndsWith(String),
}

impl PhraseSpec {
    fn rust(&self) -> String {
        match self {
            PhraseSpec::Is(phrases) => format!("Phrase::Is({})", list(phrases)),
            PhraseSpec::StartsWith(start) => format!("Phrase::StartsWith({})", literal(start)),
            PhraseSpec::EndsWith(end) => format!("Phrase::EndsWith({})", literal(end)),
        }
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
enum AddressSpec {
    Inline,
    HostEndsWith(String),
    HostStartsWith(String),
    Folder(Vec<String>),
}

impl AddressSpec {
    fn rust(&self) -> String {
        match self {
            AddressSpec::Inline => "Address::Inline".to_string(),
            AddressSpec::HostEndsWith(end) => format!("Address::HostEndsWith({})", literal(end)),
            AddressSpec::HostStartsWith(start) => {
                format!("Address::HostStartsWith({})", literal(start))
            }
            AddressSpec::Folder(folders) => format!("Address::Folder({})", list(folders)),
        }
    }
}

#[derive(Deserialize)]
#[serde(rename_all = "snake_case", deny_unknown_fields)]
enum EmbedSpec {
    Permalink(String),
    #[serde(rename = "youtube")]
    YouTube(String),
}

impl EmbedSpec {
    fn rust(&self) -> String {
        match self {
            EmbedSpec::Permalink(attribute) => format!("Embed::Permalink({})", literal(attribute)),
            EmbedSpec::YouTube(attribute) => format!("Embed::YouTube({})", literal(attribute)),
        }
    }
}
