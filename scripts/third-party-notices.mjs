#!/usr/bin/env node
// Writes THIRD_PARTY_NOTICES.md: the licence of every crate compiled into
// cohesiond and cohesion, with each licence file the crate ships, plus the code
// vendored in this repo. The web UI's bundled packages are listed by Vite in
// web/build/third-party-licenses.md (`build.license` in web/vite.config.ts).
//
// Run from anywhere with `node scripts/third-party-notices.mjs`; it reads the
// crates' sources from cargo's registry, fetching them first.

import { execFileSync } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const binaries = ['cohesiond', 'cohesion'];
const target = 'x86_64-unknown-linux-gnu';

execFileSync('cargo', ['fetch', '--locked'], { cwd: root, stdio: 'inherit' });
const metadata = JSON.parse(
	execFileSync(
		'cargo',
		['metadata', '--format-version', '1', '--locked', '--filter-platform', target],
		{ cwd: root, maxBuffer: 256 * 1024 * 1024 }
	)
);

const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));

// Everything the two binaries link, following normal dependencies only: build
// scripts and proc macros run at build time and ship nothing.
const shipped = new Set();
const queue = metadata.packages.filter((p) => binaries.includes(p.name)).map((p) => p.id);
while (queue.length) {
	const id = queue.pop();
	if (shipped.has(id)) continue;
	shipped.add(id);
	for (const dep of nodes.get(id).deps) {
		if (dep.dep_kinds.some((k) => k.kind === null)) queue.push(dep.pkg);
	}
}

const licenceFile = /^(licen[cs]e|copying|notice|copyright)/i;
const texts = (dir) =>
	readdirSync(dir, { withFileTypes: true })
		.filter((e) => e.isFile() && licenceFile.test(e.name))
		.map((e) => e.name)
		.sort()
		.map((name) => ({ name, text: readFileSync(join(dir, name), 'utf8').trim() }));

const crates = [...shipped]
	.map((id) => packages.get(id))
	.filter((p) => p.source !== null)
	.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

let out = `# Third-party notices

Cohesion is licensed under the GNU Affero General Public License, version 3
only (see LICENSE). \`cohesiond\` and \`cohesion\`, and the container image that
holds them, include the third-party software listed here, each under its own
licence.

- The web UI that \`cohesiond\` embeds and serves lists its bundled packages in
  \`third-party-licenses.md\`, written into \`web/build\` by \`npm run build\`.
- The container image is based on Debian; its packages' notices are in the
  image under \`/usr/share/doc\`.
- Every crate is used unmodified. The source of each, including those under
  MPL-2.0, is on crates.io at the version listed.

This file is generated by \`scripts/third-party-notices.mjs\`. Don't edit it by
hand.

## Vendored in this repository

`;

for (const dir of ['cohesion-js/vendor/pele']) {
	out += `### ${dir}\n\n`;
	for (const { name, text } of texts(join(root, dir))) out += `#### ${name}\n\n\`\`\`text\n${text}\n\`\`\`\n\n`;
}

out += `## Rust crates

| Crate | Version | Licence |
|---|---|---|
`;
for (const p of crates) out += `| ${p.name} | ${p.version} | ${p.license ?? p.license_file ?? 'see below'} |\n`;
// Identical texts are written once, under every crate that ships them.
const groups = new Map();
const bare = [];
for (const p of crates) {
	const files = texts(dirname(p.manifest_path));
	if (files.length === 0) bare.push(p);
	for (const { text } of files) {
		const crate = `${p.name} ${p.version}`;
		groups.has(text) ? groups.get(text).push(crate) : groups.set(text, [crate]);
	}
}
out += '\n## Licence texts\n\n';
if (bare.length) {
	out += 'These crates ship no licence file. Their licence is the standard text named in the table:\n';
	out += bare.map((p) => `${p.name} ${p.version}`).join(', ') + '.\n\n';
}
for (const [text, names] of groups) {
	out += `### ${names.join(', ')}\n\n\`\`\`text\n${text.replaceAll('```', "\'\'\'")}\n\`\`\`\n\n`;
}

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out.trimEnd() + '\n');
console.log(`Wrote THIRD_PARTY_NOTICES.md: ${crates.length} crates.`);
